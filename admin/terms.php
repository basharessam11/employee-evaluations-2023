<font><b>مقدمة</b></font>
<div>تجدون أدناه الشروط والأحكام المنظمة لاستخدامكم لمنصة قيمني وكافة الآثار القانونية التي تنتج عن استخدامكم لخدمات منصة قيمني في الشبكة العنكبوتية، حيث أن استخدام أي شخص كان لمنصة قيمني فإن هذا يُعد موافقة وقبول منه وهو بكامل أهليته المعتبرة شرعاً ونظاماً وقانوناً لكافة مواد وبنود وأحكام هذه الاتفاقية وهو تأكيد لالتزامكم بأنظمتها ولما ذُكر فيها، ونشير إليكم بأن منصة قيمني قد تكون عبارة عن (موقع إلكتروني أو تطبيق على الهواتف المحمولة أو منصة إلكترونية) وتعتبر هذه الاتفاقية سارية المفعول ونافذة بمجرد قيامكم بالموافقة عليها والبدء في التسجيل بمنصة قيمني.</div>
<br />
<br />

<font><b>المقدمة والتعريفات</b></font>
<div>يعتبر التمهيد أعلاه جزءاً لا يتجزأ من هذه الاتفاقية، كما تجدون أدناه الدلالات والتعريفات للعبارات الرئيسية المستخدمة في هذه الاتفاقية:</div>
<br />
<ul>
    <li>(منصة قيمني) ويقصد بهذه العبارة مؤسسة رجل الكهف لتقنية المعلومات، ويشمل هذا التعريف كافة أشكال رجل الكهف لتقنية المعلومات على الشبكة العنكبوتية، سواءً كانت تطبيق الكتروني أو موقع الكتروني على الشبكة، بإعتبارها المالكة لمنصة قيمني.</li>
    <li>(المشترك) ويقصد بهذه العبارة كل مشترك يسجّل في منصة قيمني لإنشاء حسابه الالكتروني، سواءً كان شخص طبيعي أو معنوي، ويشمل هذا التعريف كافة أوجه الحساب طالما أنه يقوم بنشاطه عن طريق منصة قيمني.</li>
    <li>(الحساب) ويقصد بهذه العبارة الحساب المستخدَم من قبل المشترك في منصة قيمني الالكترونية.</li>
    <li>(العميل) ويقصد بهذه العبارة كل عميل يقوم بالتقييم، وذلك عن طريق حساب المشترك الذي أسسه عبر منصة قيمني.</li>
    <li>(الاتفاقية) ويقصد بهذه العبارة قواعد وشروط وأحكام استخدام منصة قيمني الإلكترونية، أي كافة أحكام وشروط هذه الاتفاقية، والتي تحكم وتنظّم العلاقة فيما بين أطراف هذه الاتفاقية..</li>
</ul>
<br />

<font><b>أهلية المشترك</b></font>
<ul>
    <li>يقر المشترك بأنه ذا أهلية قانونية معتبرة شرعاً وقانوناً، وأن عمره لا يقل عن ثمانية عشرة عاماً، كما هو معتبر في القوانين والأنظمة المرعية بالمملكة العربية السعودية ، وأنه ذا دراية كافية بإنشاء وإدارة حساب الالكتروني عبر منصة قيمني.</li>
    <li>يقر المشترك بأنه ذا أهلية سليمة وأنه غير مصاب بأي عارض من عوارض الأهلية.</li>
    <li>يوافق المشترك بأنه في حال مخالفته لهذه المادة ” أهلية المشترك ” فإنه يتحمّل تبعات هذه المخالفة أمام الغير، حيث أن منصة قيمني لا علاقة لها بمخالفة المشترك من الناحية القانونية والنظامية والشرعية، كما أنه يحق لمنصة قيمني في هذه الحالة مساءلة المشترك بموجب أحكام المسئولية العقدية، ومطالبته بالتعويض عن الأضرار التي قد تنشأ نتيجة هذه المخالفة، ومن قبيل هذه الأضرار ما يصيب منصة قيمني في سمعتها أمام الغير.</li>
</ul>
<br />

<font><b>طبيعة التزام منصة قيمني</b></font>
<div>قد نستخدم معلوماتك الشخصية في الأغراض التالية:</div>
<ul>
    <li>إن مهمة منصة قيمني هي مجرد تقديم أدوات الدعم الالكتروني، عن طريق تأسيس حساب تقييم، حيث أن التزام منصة قيمني بموجب هذه الاتفاقية هو فقط انشاء حساب التقييم، ووضع المشترك أمام عملائه.</li>
    <li>قد توفّر منصة قيمني خدمات أخرى للمشترك كخدمات الدعم التسويقي أو خدمات التوجيه والإرشاد، وجميع خدمات منصة قيمني تخضع لمواد وبنود وأحكام اتفاقية الاستخدام هذه.</li>
    <li>أنت تعلم أن منصة قيمني تعتبر منصة إلكترونية تقنية على شبكة الانترنت تتيح للمشترك الذي يوافق على هذه الاتفاقية تأسيس حسابه الالكتروني ، وممارسة نشاطه عبر الحساب، ومهمتها تنتهي عند هذا الحد. فليس هناك أدنى مسئولية على منصة قيمني حول المخالفات التي يقوم بها المشترك أو العميل المخالفة لأحكام هذه الاتفاقية.</li>
</ul>
<br />

<font><b>ضوابط إنشاء حساب على المنصة</b></font>
<ul>
    <li>يجب أن يكون الحساب الذي تم تأسيسه وفقاً لاتفاقية استخدام منصة قيمني غير مخالف للأنظمة والقوانين في المملكة العربية السعودية، وتخلي منصة قيمني مسئوليتها عن مخالفة الحساب أو المشترك لأحكام النظام السعودي في المملكة العربية السعودية والآداب العامة، و يبقى لمنصة قيمني دائماً الحق في رفض تسجيل أي حساب لا يتوافق مع القوانين والأنظمة المرعية في المملكة العربية السعودية أو أحكام هذه الاتفاقية، وعليه فإن المشترك يقر بموجب أحكام الاتفاقية أن حسابه لا يخالف النظام العام في المملكة العربية السعودية أو الآداب العامة.</li>
    <li>لا يحق لأي شخص استخدام منصة قيمني إذا ألغي حسابه من قبل منصة قيمني أو بموجب أوامر أو أحكام قضائية.</li>
    <li>في حال قيام أي مستخدم بالتسجيل كمؤسسة أو شركة، أو مؤسسة خيرية أو جهة حكومية أو جهة اعتبارية، فإن المؤسسة أو الشركة أو الجهة المسجّلة تكون ملزمة بكافة القواعد والأحكام المذكورة في اتفاقية الاستخدام الخاصة بمنصة قيمني.</li>
    <li>يجب أن يلتزم الحساب والمشترك بالتزامات التسجيل المحددة في بند ” الحسابات والتزامات التسجيل “، وجميع قواعد وأحكام اتفاقية الاستخدام.</li>
</ul>
<br />

<font><b>الحسابات والتزامات التسجيل</b></font>
<div>فور التقدم بطلب الانضمام إلى عضوية منصة قيمني أو طلب إنشاء حساب تكون مطالباً بالإفصاح عن معلومات محددة واختيار كلمة مرور سرية لاستعمالها عند الولوج لخدمات منصة قيمني. وبعد تنشيط حسابك سوف تصبح مستخدمًا لخدمات منصة قيمني، وبذلك تكون قد وافقت على:</div>
<ul>
    <li>أن تكون مسؤولاً عن المحافظة على سرية معلومات حسابك وسرية كلمة المرور، وتكون بذلك موافقاً على إعلام منصة قيمني حالاً بأي استخدام غير مفوض به لمعلومات حسابك لدى منصة قيمني أو أي اختراق آخر لمعلوماتك السرية.</li>
    <li>لن تكون منصة قيمني بأي حال من الأحوال مسؤولًة عن أي خسارة قد تلحق بك بشكل مباشر أو غير مباشر معنوية أو مادية نتيجة كشف معلومات اسم المستخدم أو كلمة المرور أو في حال إساءة استخدام الحساب.</li>
    <li>أنت تلتزم باستخدام حسابك بنفسك، حيث أنك مسؤولاً عنه مسؤولية كاملة، وفي حال استخدام غيرك له فهذه يعني أنك قد فوّضته باستخدام الحساب باسمك ولحسابك مالم يقوم الحساب بإبلاغ إدارة منصة قيمني بعكس ذلك.</li>
    <li>أنت تلتزم عند استخدام منصة قيمني أن تستخدمها بكل جدية ومصداقية، وأن تلتزم بقواعد وأحكام اتفاقية الاستخدام وأن تلتزم بالضوابط النظامية والقانونية المعمول بها في المملكة العربية السعودية، وتعتبر ملزماً بتعويض منصة قيمني عن أي خسائر مباشرة أو غير مباشرة قد تلحق بمنصة قيمني نتيجة أي استخدام غير شرعي أو غير حقيقي أو غير مفوض لحسابك من طرفك أو من طرف أي شخص آخر حصل على مفاتيح الولوج إلى حسابك بالمنصة سواء كان لإنجاز الخدمات باستعمال اسم المستخدم وكلمة المرور أو نتيجة لإهمالك المحافظة على سرية اسم المستخدم وكلمة المرور، وسواء بتفويض منك أو بلا تفويض.</li>
    <li>أنت تلتزم بالإفصاح عن معلومات حقيقية وصحيحة ومحدثة وكاملة وقانونية عن نفسك حسبما هو مطلوب أثناء التسجيل لدى منصة قيمني وتلتزم بتحديث بياناتك في حال تغييرها في الواقع أو في حال الحاجة إلى ذلك.</li>
    <li>أن لا تضع ما يشير في حسابك إلى أي علاقة مباشرة أو غير مباشرة بين الحساب ومنصة قيمني أو إدارتها أو مُلّاكها أو منسوبيها، حيث أن منصة قيمني لا علاقة لها بما تقوم به في حسابك وهي غير مسئولة عن نشاط حسابك.</li>
    <li>إن منصة قيمني تلتزم بالتعامل مع معلوماتك الشخصية وعناوين الاتصال بك بسريّة وفقاً لأحكام سياسة الخصوصية وسرية المعلومات المعمول بها لدى منصة قيمني.</li>
    <li>سوف تكون ملزمًا بالحفاظ على بيانات التسجيل وتحديثها دائمًا للإبقاء عليها حقيقية وصحيحة وراهنة وكاملة وقانونية، وإذا أفصحت عن معلومات غير حقيقية أو غير صحيحة أو غير راهنة أو غير كاملة أو غير قانونية أو مخالفة لما جاء في اتفاقية الاستخدام، فإن منصة قيمني تمتلك الحق في وقف أو تجميد أو إلغاء عضويتك وحسابك في المنصة، وذلك دون إلحاق الأضرار بحقوق منصة قيمني الأخرى ووسائلها المشروعة في استرداد حقوقها وحماية باقي المستخدمين.</li>
    <li>لمنصة قيمني الحق في أي وقت في أن تجري أي تحقيقات تراها ضرورية سواء كانت مباشرة أو عبر طرف ثالث وتطالبك بالإفصاح عن أي معلومات إضافية أو وثائق مهما كان حجمها لإثبات هويتك أو ملكيتك للحساب الخاص بك.</li>
    <li>في حالة عدم الالتزام بأي مما ورد أعلاه فإن لإدارة منصة قيمني الحق في إيقاف أو إلغاء حسابك أو عضويتك أو حجبك من الولوج لخدمات منصة قيمني مرة أخرى. وتحتفظ كذلك بالحق في إلغاء أي حسابات غير مؤكدة وغير مثبتة أو حسابات مر عليها مدة طويلة دون نشاط.</li>
</ul>
