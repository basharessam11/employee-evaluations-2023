<font><b>الاتصالات الإلكترونية ووسائل التواصل الرسمية</b></font>
<ul>
    <li>يوافق المشترك في منصة قيمني على أن يتم التواصل معه عبر البريد الإلكتروني أو الجوال أو من خلال قيام إدارة منصة قيمني ببث رسائل عامة ترد إلى كافة المستخدمين أو إلى مستخدمين محددين حال الولوج إلى حساباتهم داخل منصة قيمني. كما يوافق المشترك في منصة قيمني على أن جميع الاتفاقيات والإعلانات والبيانات والاتصالات الأخرى التي تزود بها الكترونياً تقوم مقام مثيلاتها المكتوبة، وهي حجة قائمة بذاتها، في تلبية الاحتياجات القانونية.</li>
    <li>سوف تقوم منصة قيمني بإرسال رسائل ترويجية لتعريفك بأي تغيرات أو إجراءات أو نشاطات دعائية جديدة قد تضاف إلى منصة قيمني.</li>
</ul>
<br />

<font><b>التعديلات على اتفاقية الاستخدام والرسوم</b></font>
<ul>
    <li>أنت تعلم وتوافق على أن تقوم منصة قيمني بإعلامك عن أي تعديل على هذه الاتفاقية، وبموجبه تتضاعف التزاماتك أو تتضاءل حقوقك وفقاً لأي تعديلات قد تجري على اتفاقية الاستخدام هذه.</li>
    <li>أنت توافق على أن منصة قيمني تملك بمطلق صلاحيتها ودون تحملها المسؤولية القانونية أن تجري أي تعديلات أساسية أو فرعية على هذه الاتفاقية، ويتم إعلام المستخدمين عن هذا التعديل بأي وسيلة تقنية يتم توفيرها، ويجوز أن يكون ذلك عن طريق البريد الإلكتروني أو ببث رسالة عامة لكافة المستخدمين، وتوفّر منصة قيمني وسائل تقنية لإظهار قبول الحساب لهذا التعديل، ويكون هذا القبول قانوني ونافي للجهالة ومُلزِم للحساب والمشترك لأحكام الاتفاقية بما فيها من تعديلات.</li>
    <li>في حال الاعتراض على أي تعديل على اتفاقية الاستخدام فإن ذلك قد يكون عقبة أمام الولوج إلى الحساب، حيث أنه للاستفادة من خدمات منصة قيمني يجب الموافقة على هذه الاتفاقية وعلى أي تعديل يطرأ عليها، ولذلك في حالة عدم قبول التعديل تأمل منكم منصة قيمني التوقف عن استخدام خدماتها حيث أن مجرد ولوجكم إلى حسابكم في منصة قيمني أو استخدامكم لمنصة قيمني يُعد قبولًا منكم للتعديلات وموافقة كاملة تامة نافية للجهالة، وتسعد منصة قيمني الإجابة على استفساراتكم بشأن هذه الاتفاقية واستقبال أي اقتراحات يراها المشترك.</li>
    <li>على المشترك دفع كافة الرسوم المستحقة بالمنصة مضافاً إليها أي نفقات أخرى تضيفها منصة قيمني، على أن يتم السداد بواسطة الوسائل المعتمدة والمحددة والمتاحة عن طريق منصة قيمني.</li>
    <li>قد تفرض منصة قيمني رسومًا على المشتركين أو الحسابات وذلك يعتمد على العروض أو الباقات التي ينضمون إليها أو طريقة استخدامهم للمنصة.</li>
    <li>تحتفظ منصة قيمني بحقها في إضافة أو زيادة أو خفض أو خصم أي رسوم أو نفقات بموجب قواعد وأحكام اتفاقية الاستخدام، على أي من المشتركين أي كان سبب تسجيلهم.</li>
</ul>
