<font><b>معلوماتك الشخصية ومعلومات تفاصيل العمليات</b></font>
<ul>
    <li>لا مانع لديك بأن تمنح منصة قيمني حقاً غير محدود، وعالمي، ودائم وغير قابل للإلغاء، ومعفي من المصاريف، ومرخص باستخدام معلومات أو مواد شخصية أو غير ذلك مما وفرتها أو زودت بها المنصة أو أعلنتها على المنصة من خلال انضمامك إليها أو تأسيسك لحسابك، وذلك عبر النماذج المخصصة للتواصل و التسجيل، أو عبر أية رسالة إلكترونية أو أي من قنوات الاتصال المتاحة بالمنصة. وذلك بهدف تحقيق أي من المصالح التي تراها المنصة.</li>
    <li>أنت الوحيد المسؤول عن المعلومات التي قمت بإرسالها أو نشرها وينحصر دور منصة قيمني بالسماح لك بعرض هذه المعلومات عن طريق منصة قيمني ومن خلال قنواتها الإعلانية.</li>
    <li>تخضع سرية معلومات الحسابات والمشتركين لقواعد “سياسة الخصوصية وسرية المعلومات” الخاصة بمنصة قيمني.</li>
</ul>
<br />

<font><b>تعهد المشترك بـالالتزام بالقوانين والأنظمة في المملكة العربية السعودية</b></font>
<ul>
    <li>يتعهّد المشترك بالالتزام بكافة القوانين والأنظمة المعمول بها داخل المملكة العربية السعودية أثناء استخدامه لمنصة قيمني، وكذا القوانين والشروط و الأحكام المعمول بها والمُنظِّمة لاستخدام فضاء الإنترنت واتفاقية الاستخدام وسياسة الخصوصية وسرية المعلومات المعمول بها لدى منصة قيمين.</li>
    <li>في حال مخالفة المشترك أو الحساب لما ورد في هذه الاتفاقية فإنه يقر بحق منصة قيمني في اتخاذ أي من الاجراءات التالية وهي على سبيل المثال لا الحصر: التنبيه، إيقاف الخدمة وإغلاق الحساب.</li>
</ul>
<br />

<font><b>الحقوق</b></font>
<ul>
    <li>كافة المحتويات المتواجدة على منصة قيمني، إلكترونية كانت أو غير ذلك، مكتوبة أو غير مكتوبة، على سبيل المثال لا الحصر: النصوص المكتوبة وغير المكتوبة – التصاميم الجرافيكية – الأفكار التقنية – الشعارات – العروض – أيقونات الأزرار – الرموز – المقاطع الصوتية – البيانات المجمّعة والبرامج الإلكترونية، هي ملك لمنصة قيمني وحقوقها محفوظة لمنصة قيمني، ولا يحق لكائنًا من كان أن يستخدمها بأي شكل من الأشكال سواء كان استخدام مباشر أو غير مباشر أو عن طريق طرف ثالث.</li>
    <li>تنوه إدارة منصة قيمني على أنها سوف تتخذ اللازم حيال التجاوز والتعدي على أي من حقوق منصة قيمني أو ملكيتها الفكرية.</li>
    <li>لا تتحمّل منصة قيمني المسؤولية في حال التعدي على حقوق الملكية الفكرية المملوكة للمشتركين في المنصة أو للحسابات المسجّلة لديها.</li>
</ul>
<br />

<font><b>الملكية الفكرية</b></font>
<div>يحترم المشترك حقوق الملكية الفكرية الخاصة بمنصة قيمني والتي من ضمنها منصة قيمني نفسها، والكلمات والشعارات والرموز الأخرى الخاصة بمنصة قيمني أو المعروضة على منصة قيمني حيث أن منصة قيمني وكل حق يتبع منصة قيمني، هي حقوق محمية بموجب حقوق الملكية الفكرية وقوانين العلامات التجارية وتعد ملكية خالصة لمنصة قيمني ولا يحق بأي حال من الأحوال التعدي عليها أو استخدامها دون تفويض من إدارة منصة قيمني.</div>
<br />
<br />

<font><b>مسئولية منصة قيمني</b></font>
<ul>
    <li>منصة قيمني لا تتحمل أي مطالبات تنشأ عن أخطاء أو إهمال، سواء كانت ناتجة بشكل مباشر أو غير مباشر أو عرضي أو عن طريق طرف ثالث.</li>
    <li>منصة قيمني لا تتحمل أي مطالبات أو مسئوليات نشأت نتيجة خسائر مالية أو تشويه سمعة أو قذف أو أي أضرار تنشأ نتيجة لسوء استخدام أو إساءة استخدام أو عدم قدرة على استخدام منصة قيمني.</li>
    <li>منصة قيمني أو مسؤوليها أو منسوبيها أو مُلّاكها غير مسئولين عن أي مطالبة أو نزاع أو تكاليف أو أضرار أو أي مسئولية أو أي خسارة مباشرة أو غير مباشرة لأي طرف نشأت عن فعل قام به أحد المستخدمين للمنصة.</li>
    <li>منصّة قيمني ومنسوبيها وملّاكها ومن يمثّلها ويمثّلهم لا علاقة لهم بأي نشاط غير شرعي أو غير نظامي يقوم به الحساب، أو أي نشاط يخالف الأنظمة والتعليمات المرعيّة في المملكة العربية السعودية.</li>
    <li>تنوه إدارة منصة قيمني على كافة المشتركين إلى أنها في حال ملاحظاتها لأي أنشطة مشبوهة يجري التخطيط لارتكابها أو جاري ارتكابها أو جرت على منصة قيمني فإنها سوف تتقدّم إلى إبلاغ السلطات المختصة عن هذه الأنشطة. وهي غير مسئولة بأي حال عن هذه المخالفات التي تتم دون علم أو ملاحظة منصة قيمني.</li>
</ul>
<br />

<font><b>سرية المعلومات</b></font>
<ul>
    <li>الشبكة العنكبوتية ( الإنترنت ) ليس وسيلة آمنة تماما، وسرية المعلومات الشخصية لا يمكن أن تكون مضمونة 100% في فضاء الإنترنت.</li>
    <li>تتخذ منصة قيمني معايير ذات جودة عالية لحماية المشتركين والحسابات ومنع وصول شخص غير مفوض إلى معلومات المشتركين الشخصية أو حساباتهم، وحفظها.</li>
    <li>منصة قيمني ليس لها سيطرة على أفعال أي طرف ثالث، أو الغير، مثل صفحات الانترنت الأخرى الموصولة عن طريق روابط إلى المنصة أو أطراف ثالثة تدعي أنها تمثلك وتمثل آخرين.</li>
    <li>أنت تعلم وتوافق على أن منصة قيمني قد تستخدم معلوماتك التي زودتها بها، بهدف تقديم الخدمات لك في منصة قيمني، ولإرسال رسائل تسويقية لك ، وان سياسة الخصوصية في منصة قيمني تضبط عمليات الجمع والمعالجة والاستخدام والتحويل لمعلومات هويتك الشخصية، وتخضع قواعد سرية المعلومات لـ “سياسة الخصوصية وسرية المعلومات” الخاصة بمنصة قيمني.</li>
</ul>
<br />

<font><b>سياسة الاستبدال والاسترجاع</b></font>
<ul>
    <li>يمكن إلغاء الاشتراك في أي باقة واسترداد رسوم الاشتراك خلال 14 يوم من تنفيذ عملية الدفع.</li>
    <li>يمكن إلغاء رصيد الرسائل الاعلانية خلال 14 يوم من تنفيذ عملية الدفع بشرط عدم استخدام أي جزء من الرصيد.</li>
    <li>في حال إلغاء أي مدفوعات تمت لصالح منصة قيمني، سيتم احتساب وخصم رسوم التحويل البنكي، بالإضافة إلى أي رسوم اخرى يتم فرضها في سبيل تحقيق ذلك.</li>
</ul>
<br />

<font><b>إلغاء العضوية أو الحساب</b></font>
<div>إن منصة قيمني بحسب اتفاقية الاستخدام وبحسب القوانين والأنظمة المرعية بالمملكة العربية السعودية قد تلجأ إلى وقف مؤقت أو دائم للحساب أو سحب وإلغاء عضوية المشترك أو تحديد قدرات المشترك على الولوج إلى خدمات منصة قيمني، في حالة:</div>
<ul>
    <li>انتهاك قواعد وأحكام اتفاقية الاستخدام.</li>
    <li>إذا لم يكن بإمكان منصة قيمني توثيق أي من معلومات المستخدم المقدمة إليها.</li>
    <li>إذا قررت منصة قيمني أن نشاطات المستخدم مخالفة للقانون أو أن نشاطات المستخدم قد تتسبب لمستخدمين آخرين أو لمنصة قيمني بمتاعب أو مخالفات قانونية.</li>
    <li>قد تلجأ منصة قيمني “بحسب تقييمها” إلى إعادة نشاط المستخدمين الموقوفين، حيث أن المستخدم الذي أوقف نشاطه نهائياً أو أُلغيت عضويته، قد لا يكون بإمكانه التسجيل أو استعادة حسابه في منصة قيمني أو استخدام المنصة بأي طريقة كانت مهما كانت الظروف، لحين السماح له بإعادة نشاطه في منصة قيمني من قبل إدارة منصة قيمني ومع ذلك فإن المستخدم في حال انتهاكه لاتفاقية الاستخدام هذه فإن منصة قيمني تحتفظ بحقها في استعادة أو المطالبة بأي مبالغ مستحقة لمنصة قيمني على المستخدم وأي خسائر أو أضرار تسبب بها المشترك لمنصة قيمني كما أن لمنصة قيمني الحق باتخاذ الإجراءات القانونية أو اللجوء إلى السلطات القضائية في المملكة العربية السعودية أو السلطات في بلد المشترك ضد المستخدم حسبما تراه منصة قيمني مناسباً.</li>
    <li>إن منصة قيمني لا تتنازل عن حقها في اتخاذ الإجراءات المناسبة حيال أي انتهاك يحدث لقواعد وأحكام اتفاقية الاستخدام ولغيرها من أفعال الانتهاك المشابهة، وكذلك إن منصة قيمني لا تلتزم في القيام باتخاذ أي اجراءات ضد أي انتهاك يحدث لاتفاقية الاستخدام وإنما يخضع هذا الأمر لتقدير إدارة منصة قيمني وإدارتها القانونية.</li>
</ul>
<br />

<font><b>نظام الجرائم المعلوماتية السعودي</b></font>
<div>يلتزم المشتركين بعدم مخالفة أي من أحكام نظام الجرائم المعلوماتية السعودي، وفي حال مخالفتهم لأحكام نظام الجرائم المعلوماتية السعودي فإن هذا يخضع لمسئولتيهم المحضة ولإدارتهم، وليس هناك أي مسئولية تقع على عاتق منصة قيمني من جراء مخالفة الحساب للأنظمة المرعية، حيث أن المشترك هو المسئول عن حسابه وعن تعامله مع عملائه مسئولية كاملة، ولمنصة قيمني دائماً الحق في اتخاذ ما تراه مناسباً عن أي حساب أو مشترك يخالف أحكام نظام الجرائم المعلوماتية السعودي، سواءً عن طريق ابلاغ السلطات الرسمية أو الاكتفاء بإغلاق الحساب أو إلغاء عضوية المشترك لدى المنصة.</div>
<br />
<br />

<font><b>تقييد الولوج أو العضوية</b></font>
<div>بدون إلحاق الضرر بحقوق المشتركين الأخرى، يمكن لمنصة قيمني وقف أو إلغاء عضوية المشترك أو تقييد ولوج المشترك إلى خدمات المنصة في أي وقت وبدون إنذار ولأي سبب، ودون تحديد.</div>
<br />
<br />

<font><b>مسئولية المشترك</b></font>
<div>يوافق المشترك على تحمل المسئولية ووقاية منصة قيمني أو منسوبيها أو مُلّاكها أو المتفرعين عنها من أي ضرر قد يقع على منصة قيمني من جراء مخالفات المشترك ، كما يلتزم برفع أي ضرر أو منع أي ضرر قد يلحق بمنصة قيمني أو بمنسوبيها أو بأحدهم من جراء مطالبات أو خسائر أو أعطال أو تكاليف أو نفقات أو رسوم نتجت بسبب إساءة استخدام المشترك أو سوء استخدام المستخدم ونتج عن ذلك خرق لاتفاقية الاستخدام أو الأنظمة والقوانين المرعية بالمملكة العربية السعودية أو تعدي على حقوق المشتركين أو عملائهم أو أطراف ثالثة أو شكوى من أحد المستخدمين أو العملاء أو أطراف ثالثة.</div>
<br />
<br />

<font><b>العلاقة والإشعارات بين منصة قيمني والمشتركين</b></font>
<div>لا تتضمن أي من قواعد وأحكام اتفاقية الاستخدام هذه إشارة إلى وجود شراكة بين أي مشترك ومنصة قيمني، ولا تسمح منصة قيمني لأي مشترك في أي حال من الأحوال بالإشارة المباشرة أو الغير مباشرة أو الإملاء إلى وجود علاقة أي كان نوعها سواء كانت مباشرة أو غير مباشرة بينه كمشترك وبين منصة قيمني أو إدارتها، وأن أي إشعارات يرغب المشترك في إرسالها إلى منصة قيمني، عليه أن يقوم بإرسالها عبر البريد الإلكتروني وتقوم منصة قيمني بالرد على الرسالة الإلكترونية. وأنت كمشترك توافق على أن أي إشعارات ترسل إليك من منصة قيمني سوف تُسلّم إليك بواسطة البريد الإلكتروني أو الجوال الذي قمت بتزويد منصة قيمني به خلال عملية التسجيل.</div>
<br />
<br />

<font><b>نقل الحقوق والالتزامات</b></font>
<div>أنت كمشترك لا تملك الحق في الاعتراض على تصرفات إدارة منصة قيمني حيال منصة قيمني سواء كانت هذه التصرفات على سبيل المثال لا الحصر : تمس كيان منصة قيمني أو التزاماتها أو ملكيتها أو مسئولياتها أو تصرفات تقنية أو تصرفات إدارية تتعلّق بمنصة قيمني، وليست مُلزَمة منصة قيمني بإبلاغك، و لمنصة قيمني إن رأت أهمية إبلاغك عن أي من هذه التصرفات أن تقوم بإبلاغك وفقاً لإرادتها المحضة، وذلك بحسب قواعد وأحكام اتفاقية الاستخدام.</div>
<br />
<br />

<font><b>القانون والتشريع المطبق</b></font>
<div>اتفاقية الاستخدام هذه محكومة ومصاغة بحسب القوانين والأنظمة والتشريعات المعمول بها والسارية في المملكة العربية السعودية، وهي خاضعة تمامًا وكليًا للتشريع المعمول به لدى السلطات في المملكة العربية السعودية.</div>
<br />
<br />

<font><b>المنشورات الدعائية الورقية والإلكترونية والعروض الخاصة بمنصة قيمني</b></font>
<ul>
    <li>تسري قواعد وأحكام اتفاقية الاستخدام هذه على كافة المنشورات الدعائية الورقية والإلكترونية عبر مختلف منصات النشر وعبر مختلف وسائل التواصل الاجتماعي.</li>
    <li>المنشورات والمطبوعات المذكورة هي وسيلة ترويجية لمنصة قيمني.</li>
    <li>إن المنشورات قابلة للتغيير وهي غير ملزمة لمنصة قيمني فيما يخص ثبات أسعار الخدمات أو الباقات أو العروض وتغيير الأسعار يخضع للمتغيرات التي تطرأ على منصة قيمني أو الحسابات أو المشتركين.</li>
    <li>إن أي عروض تضعها منصة قيمني هي عبارة عن عروض مؤقتة ويتم تحديدها بفترة زمنية محددة، ولا تلتزم منصة قيمني بتمديد الفترة الزمنية أو بالاستمرار في الفترة الزمنية المحددة حيث أنها تملك الحق في الاكتفاء أو تحديد استحقاق أي مستخدم لهذا العرض أو إلغاء هذا العرض في أي وقت.</li>
</ul>
<br />

<font><b>أحكام عامة</b></font>
<div>في حال إلغاء أي مادة واردة أو بند ورد في اتفاقية الاستخدام هذه أو أن هناك أي مادة واردة أو أي بند وارد في اتفاقية الاستخدام لم يعد نافذًا، فإن مثل هذا الأمر لا يلغي صلاحية باقي المواد والبنود والقواعد والأحكام الواردة في اتفاقية الاستخدام وتظل سارية حتى إشعار آخر من إدارة منصة قيمني.</div>
<div>اتفاقية الاستخدام هذه – والتي تعدل بين حين وآخر بحسب مقتضى الحال – تُشكّل آلية العمل والتفاهم والاتفاق والتعاقد بين المشترك وحسابه ومنصة قيمني فقط لا غير، ويلتزم المشترك والحساب بالالتزام بأحكام هذه الاتفاقية، كما يوافق المشترك على أن يضع في عين الاعتبار ما يلي:</div>
<ul>
    <li>اتفاقية الاستخدام هذه سارية على كافة المستخدمين لمنصة قيمني وهي المُنظّمة للعلاقة وهي العقد فيما بين المشترك و منصة قيمني فقط لا غير، بغض النظر عن أي شكل نظامي أو كيان قانوني أو مؤسسي أو تجاري أو خيري يتخذه المشترك أو الحساب. أما فيما يخص العلاقة فيما بين المشترك وعملائه فإنه تخضع لعلاقة قانونية مستقلة ولها ضوابطها الخاصة الجارية فيما بينهم.</li>
    <li>المشترك الذي ينضم الى منصة قيمني عن طريق (كود تسويقي) فإنه بذلك يمنحنا الحق في إطلاع المسوق الذي قام بالتسجيل بواسطته على معلومات المشترك الأساسية وحسابه.</li>
