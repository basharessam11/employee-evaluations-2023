<font><b>مقدمة</b></font>
<ul>
    <li>إننا نهتم بشكل كبير بخصوصية زوار موقعنا، ونتعهد بحمايتها. تشرح هذه السياسة كيفية التصرف في معلوماتك الشخصية.</li>
    <li>بموافقتك على استخدامنا لملفات تعريف الارتباط وفقا لبنود هذه السياسة عند زيارتك لموقعنا الإلكتروني لأول مرة فإنك تسمح لنا باستخدام ملفات تعريف الارتباط في كل مرة تزور فيها موقعنا.</li>
</ul>
<br />

<font><b>جمع المعلومات الشخصية</b></font>
<ul>
    <li>قد يتم جمع وتخزين واستخدام المعلومات الشخصية التالية: معلومات حول جهاز الكمبيوتر الخاص بك بما في ذلك عنوان بروتوكول الإنترنت الخاص بك، والموقع الجغرافي، ونوع المتصفح والإصدار، ونظام التشغيل.</li>
    <li>معلومات حول زياراتك لهذا الموقع واستخدامه بما في ذلك مصدر الإحالة، ومدة الزيارة، وما تشاهده على الصفحة، ومسارات التصفح في الموقع.</li>
    <li>المعلومات التي تدخلها عند التسجيل في موقعنا الإلكتروني، مثل عنوان بريدك الإلكتروني.</li>
    <li>المعلومات التي تدخلها عند إنشاء ملف تعريف على موقعنا – على سبيل المثال، اسمك، صور ملفك الشخصي، الجنس، تاريخ الميلاد، الحالة الاجتماعية، الاهتمامات والهوايات، الحالة التعليمية، وتفاصيل الوظيفة.</li>
    <li>المعلومات، مثل اسمك وعنوان بريدك الإلكتروني، التي تدخلها من أجل إعداد اشتراكك في رسائل البريد الإلكتروني و / أو الرسائل الإخبارية لدينا.</li>
    <li>المعلومات التي تدخلها أثناء استخدام الخدمات على موقعنا.</li>
    <li>المعلومات التي يدخلها عملائك أثناء استخدام الخدمات على موقعنا.</li>
    <li>المعلومات التي يتم إنشاؤها أثناء استخدام موقعنا الإلكتروني، بما في ذلك مواعيد وتكرار استخدامك للموقع والظروف التي تستخدم فيها الموقع.</li>
    <li>المعلومات المتعلقة بأي شيء تشتريه، أو الخدمات التي تستخدمها، أو المعاملات التي تجريها من خلال موقعنا الإلكتروني، والتي تشمل اسمك وعنوانك ورقم هاتفك وعنوان بريدك الإلكتروني وتفاصيل بطاقة الائتمان.</li>
    <li>المعلومات التي تنشرها على موقعنا الإلكتروني بغرض مشاركتها على الإنترنت، والتي تشمل اسم المستخدم الخاص بك وصور ملفك الشخصي ومحتوى مشاركاتك.</li>
    <li>المعلومات الواردة في أي مراسلات ترسلها إلينا عبر البريد الإلكتروني أو عبر موقعنا الإلكتروني، بما في ذلك المحتوى المشترك والبيانات الوصفية.</li>
    <li>أي معلومات شخصية أخرى ترسلها إلينا.</li>
</ul>
<div>قبل أن تفصح لنا عن المعلومات الشخصية الخاصة بشخص آخر، ينبغي عليك الحصول على موافقة هذا الشخص على كشف هذه المعلومات الشخصية ومعالجتها وفقا لهذه السياسة.</div>
<br />
<br />

<font><b>استخدام معلوماتك الشخصية</b></font>
<div>قد نستخدم معلوماتك الشخصية في الأغراض التالية:</div>
<ul>
    <li>إدارة موقعنا وأعمالنا على شبكة الإنترنت.</li>
    <li>تخصيص موقعنا على شبكة الإنترنت ليكون أكثر ملاءمة بالنسبة لك.</li>
    <li>تمكينك من استخدام الخدمات المتاحة على موقعنا.</li>
    <li>توفير الخدمات المشتراة من خلال موقعنا على شبكة الإنترنت.</li>
    <li>إرسال البيانات والفواتير وإشعارات الدفع لك، وتحصيل المدفوعات منك.</li>
    <li>إرسال رسائل تجارية إليك.</li>
    <li>إرسال إشعارات عبر البريد الإلكتروني إليك.</li>
    <li>إرسال نشرة البريد الإلكتروني إليك (يمكنك إبلاغنا في أي وقت إذا لم تعد تحتاج إلى النشرة الإخبارية).</li>
    <li>إرسال المراسلات التسويقية المتعلقة بأعمالنا أو أعمال الجهات الخارجية التي تم اختيارها من قبلنا والتي نعتقد أنها قد تهمك، عن طريق البريد الإلكتروني أو أي تقنية أخرى (يمكنك إبلاغنا في أي وقت إذا لم تعد تحتاج إلى هذه المراسلات التسويقية).</li>
    <li>تزويد الأطراف الثالثة بمعلومات إحصائية عن مستخدمينا.</li>
    <li>التعامل مع الاستفسارات والشكاوى التي تقدمها أنت أو تقدم لنا بشأنك على موقعنا.</li>
    <li>حماية موقعنا من الاحتيال والحفاظ على أمنه.</li>
    <li>التحقق من الامتثال للشروط والأحكام التي تحكم استخدام موقعنا الإلكتروني (بما في ذلك مراقبة الرسائل الخاصة المرسلة عبر خدمة الرسائل الخاصة بموقعنا).</li>
    <li>إذا قمت أو قام أي شخص اخر بتقديم أي معلومات عن طريق حسابك على موقعنا أو تطبيقنا، فلنا الحق بنشر هذه المعلومات واستخدامها وتحليلها والانتفاع بها بأي شكل نراه.</li>
    <li>استخدامات أخرى.</li>
</ul>
